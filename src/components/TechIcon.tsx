export function TechIcon({ name, className }: { name: string; className?: string }) {
    const resolved = iconAliases[name] ?? iconAliases[name.toUpperCase()] ?? name;
    const Icon = iconMap[resolved];
    if (!Icon) return null;
    return <Icon className={className} />;
}
